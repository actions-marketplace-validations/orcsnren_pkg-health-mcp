import { describe, expect, it } from "vitest";
import { detectManifest, githubSpec, isLockFile, isManifestFilename, parseManifest } from "./manifest.js";

const names = (deps: { name: string; ecosystem: string; dev?: boolean }[]) =>
  deps.map((d) => `${d.ecosystem}:${d.name}${d.dev ? " (dev)" : ""}`);

describe("githubSpec", () => {
  it.each([
    ["a/b", "a/b"],
    ["github:a/b#v1.2.0", "a/b"],
    ["a/b.git#semver:^1", "a/b"],
    ["git+https://github.com/a/b.git", "a/b"],
    ["git+ssh://git@github.com/a/b.git#abc123", "a/b"],
    ["git+https://github.com/a/b.git@v2.0#egg=b", "a/b"],
    ["https://codeload.github.com/a/b/tar.gz/abc", "a/b"],
    ["github.com/a/b/abc123", "a/b"],
  ])("%s", (spec, expected) => {
    expect(githubSpec(spec)).toBe(expected);
  });

  it("ignores relative paths and non-GitHub hosts", () => {
    expect(githubSpec("./a/b")).toBeNull();
    expect(githubSpec("../b")).toBeNull();
    expect(githubSpec("git+https://gitlab.com/a/b.git")).toBeNull();
    expect(githubSpec("^1.2.3")).toBeNull();
  });
});

describe("detectManifest", () => {
  it("detects lock files by name", () => {
    expect(detectManifest("{}", "some/dir/package-lock.json")).toBe("package-lock.json");
    expect(detectManifest("{}", "npm-shrinkwrap.json")).toBe("package-lock.json");
    expect(detectManifest("", "yarn.lock")).toBe("yarn.lock");
    expect(detectManifest("", "pnpm-lock.yaml")).toBe("pnpm-lock.yaml");
    expect(detectManifest("", "poetry.lock")).toBe("poetry.lock");
    expect(detectManifest("", "uv.lock")).toBe("uv.lock");
  });

  it("detects lock files by content", () => {
    expect(detectManifest('{"lockfileVersion":3,"packages":{}}')).toBe("package-lock.json");
    expect(detectManifest("lockfileVersion: '9.0'\n")).toBe("pnpm-lock.yaml");
    expect(detectManifest("# yarn lockfile v1\n")).toBe("yarn.lock");
    expect(detectManifest('__metadata:\n  version: 8\n')).toBe("yarn.lock");
    expect(detectManifest('version = 1\nrequires-python = ">=3.12"\n\n[[package]]\nname = "x"\n')).toBe("uv.lock");
    expect(detectManifest('[[package]]\nname = "x"\nversion = "1"\n')).toBe("poetry.lock");
  });

  it("knows which kinds are lock files and which names are allowed", () => {
    expect(isLockFile("yarn.lock")).toBe(true);
    expect(isLockFile("package.json")).toBe(false);
    expect(isManifestFilename("/repo/package-lock.json")).toBe(true);
    expect(isManifestFilename("requirements-dev.txt")).toBe(true);
    expect(isManifestFilename("/etc/passwd")).toBe(false);
    expect(isManifestFilename("package.json.bak")).toBe(false);
  });
});

describe("package-lock.json", () => {
  const v3 = JSON.stringify({
    lockfileVersion: 3,
    packages: {
      "": { name: "root", dependencies: { express: "^4" } },
      "node_modules/express": { version: "4.21.0" },
      "node_modules/express/node_modules/debug": { version: "2.6.9" },
      "node_modules/@types/node": { version: "22.0.0", dev: true },
      "node_modules/fsevents": { version: "2.3.3", devOptional: true },
      "node_modules/my-alias": { name: "lodash", version: "4.17.21" },
      "node_modules/gh": { version: "1.0.0", resolved: "git+ssh://git@github.com/a/b.git#abc" },
      "node_modules/local": { resolved: "packages/local", link: true },
      "node_modules/bundled": { version: "1.0.0", inBundle: true },
      "packages/local": { version: "0.0.0" },
    },
  });

  it("reads v2/v3 lock files including nested and scoped packages", () => {
    expect(names(parseManifest(v3, "package-lock.json"))).toEqual([
      "npm:express",
      "npm:debug",
      "npm:lodash",
      "github:a/b",
    ]);
    expect(names(parseManifest(v3, "package-lock.json", true))).toContain("npm:@types/node (dev)");
  });

  it("reads v1 lock files", () => {
    const v1 = JSON.stringify({
      lockfileVersion: 1,
      dependencies: {
        express: { version: "4.18.0", dependencies: { debug: { version: "2.6.9" } } },
        jest: { version: "29.0.0", dev: true },
        local: { version: "file:../local" },
      },
    });
    expect(names(parseManifest(v1, "package-lock.json", true))).toEqual(["npm:express", "npm:debug", "npm:jest (dev)"]);
  });
});

describe("yarn.lock", () => {
  it("reads Yarn classic", () => {
    const lock = `# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz"

debug@2.6.9, debug@^2.0.0:
  version "2.6.9"

my-lodash@npm:lodash@^4:
  version "4.17.21"

"gh@github:a/b#main":
  version "1.0.0"
`;
    expect(names(parseManifest(lock, "yarn.lock"))).toEqual([
      "npm:@babel/core",
      "npm:debug",
      "npm:lodash",
      "github:a/b",
    ]);
  });

  it("reads Yarn Berry and skips workspaces", () => {
    const lock = `__metadata:
  version: 8
  cacheKey: 10c0

"debug@npm:^4.3.4":
  version: 4.3.7
  resolution: "debug@npm:4.3.7"

"root@workspace:.":
  version: 0.0.0-use.local

"resolve@patch:resolve@npm%3A^1.22.0#optional!builtin<compat/resolve>":
  version: 1.22.8
`;
    expect(names(parseManifest(lock, "yarn.lock"))).toEqual(["npm:debug", "npm:resolve"]);
  });
});

describe("pnpm-lock.yaml", () => {
  it("reads v9", () => {
    const lock = `lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      react:
        specifier: ^18
        version: 18.3.1

packages:

  '@types/react@18.3.3':
    resolution: {integrity: sha512-x}

  react-dom@18.3.1(react@18.3.1):
    resolution: {integrity: sha512-y}

  b@https://codeload.github.com/a/b/tar.gz/abc:
    resolution: {tarball: https://codeload.github.com/a/b/tar.gz/abc}

snapshots:

  react@18.3.1: {}
`;
    expect(names(parseManifest(lock, "pnpm-lock.yaml"))).toEqual([
      "npm:@types/react",
      "npm:react-dom",
      "github:a/b",
    ]);
  });

  it("reads v6 with dev flags and git dependencies", () => {
    const lock = `lockfileVersion: '6.0'

packages:

  /vitest@1.6.0(@types/node@20.0.0):
    resolution: {integrity: sha512-z}
    dev: true

  /express@4.19.2:
    resolution: {integrity: sha512-w}
    dev: false

  github.com/a/b/abc123:
    resolution: {tarball: https://codeload.github.com/a/b/tar.gz/abc123}
    name: b
    dev: false
`;
    expect(names(parseManifest(lock, "pnpm-lock.yaml", true))).toEqual([
      "npm:vitest (dev)",
      "npm:express",
      "github:a/b",
    ]);
    expect(names(parseManifest(lock, "pnpm-lock.yaml"))).toEqual(["npm:express", "github:a/b"]);
  });

  it("reads v5 path keys", () => {
    const lock = `lockfileVersion: 5.4

packages:

  /@babel/core/7.24.0:
    dev: true

  /react-dom/18.2.0_react@18.2.0:
    dev: false
`;
    expect(names(parseManifest(lock, "pnpm-lock.yaml", true))).toEqual(["npm:@babel/core (dev)", "npm:react-dom"]);
  });
});

describe("poetry.lock and uv.lock", () => {
  it("reads poetry.lock", () => {
    const lock = `[[package]]
name = "requests"
version = "2.32.3"
description = "HTTP"
optional = false
python-versions = ">=3.8"

[package.dependencies]
idna = ">=2.5"

[[package]]
name = "pytest"
version = "8.3.0"
category = "dev"

[[package]]
name = "mylib"
version = "0.1.0"

[package.source]
type = "git"
url = "https://github.com/a/mylib.git"
reference = "main"

[[package]]
name = "local"
version = "0.0.1"

[package.source]
type = "directory"
url = "../local"

[metadata]
lock-version = "2.0"
`;
    expect(names(parseManifest(lock, "poetry.lock", true))).toEqual([
      "pypi:requests",
      "pypi:pytest (dev)",
      "github:a/mylib",
    ]);
    expect(names(parseManifest(lock, "poetry.lock"))).toEqual(["pypi:requests", "github:a/mylib"]);
  });

  it("reads uv.lock", () => {
    const lock = `version = 1
requires-python = ">=3.12"

[[package]]
name = "demo"
version = "0.1.0"
source = { editable = "." }

[[package]]
name = "httpx"
version = "0.27.0"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "fork"
version = "1.0"
source = { git = "https://github.com/a/fork?rev=main#abc123" }
`;
    expect(names(parseManifest(lock, "uv.lock"))).toEqual(["pypi:httpx", "github:a/fork"]);
  });
});
